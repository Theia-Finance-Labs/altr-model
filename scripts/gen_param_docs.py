def render_html(params: list[Param]) -> str:
    data = json.dumps([p.as_dict() for p in params], ensure_ascii=False).replace("</", "<\\/")
    return (HTML_TEMPLATE.replace("__DATA__", data).replace("__COUNT__", str(len(params)))
            .replace("__BANNER__", html.escape(BANNER)))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--conf", default="conf/base", type=Path)
    ap.add_argument("--out", default="docs", type=Path)
    args = ap.parse_args()
    params = collect(args.conf)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "parameters.md").write_text(render_md(params))
    (args.out / "parameters.html").write_text(render_html(params))
    print(f"{len(params)} parameters -> {args.out / 'parameters.md'}, {args.out / 'parameters.html'}")


if __name__ == "__main__":
    main()
