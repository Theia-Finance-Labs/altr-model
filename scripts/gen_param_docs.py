"""Generate the ALTR parameter reference from the comment blocks in conf/base.

Every key in conf/base/parameters*.yml carries a comment block in a fixed
schema (meaning / unit / default / source / status). This script parses those
blocks and writes:

  docs/parameters.md    — GENERATED markdown table, one row per key
  docs/parameters.html  — GENERATED single-file explorer (search, filters)

Run:  uv run python scripts/gen_param_docs.py [--conf conf/base] [--out docs]
"""
from __future__ import annotations

import argparse
import html
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

FIELDS = ("meaning", "unit", "default", "source", "status")
KEY_RE = re.compile(r"^(?P<indent>\s*)(?P<key>[A-Za-z0-9_\"'][^:#]*?)\s*:\s*(?P<value>.*)$")
FIELD_RE = re.compile(r"^#\s*(?P<field>meaning|unit|default|source|status):\s*(?P<text>.*)$")


@dataclass
class Param:
    key: str
    file: str
    value: str
    line: int
    meaning: str = ""
    unit: str = ""
    default: str = ""
    source: str = ""
    status: str = ""
    tier: str = "advanced"

    def as_dict(self) -> dict:
        return {
            "key": self.key, "file": self.file, "value": self.value, "line": self.line,
            **{f: getattr(self, f) for f in FIELDS}, "tier": self.tier,
        }


@dataclass
class _Block:
    fields: dict = field(default_factory=dict)
    current: str | None = None

    def feed(self, comment: str) -> None:
        m = FIELD_RE.match(comment)
        if m:
            self.current = m.group("field")
            self.fields[self.current] = m.group("text").strip()
        elif self.current and comment.startswith("#"):
            self.fields[self.current] += " " + comment.lstrip("#").strip()

    def reset(self) -> None:
        self.fields, self.current = {}, None


def parse_file(path: Path, tier: str) -> list[Param]:
    """Attach each schema comment block to the next key at the block's indent."""
    params: list[Param] = []
    stack: list[tuple[int, str]] = []  # (indent, key) for nested paths
    block = _Block()
    for lineno, raw in enumerate(path.read_text().splitlines(), start=1):
        stripped = raw.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            block.feed(stripped)
            continue
        if stripped.startswith("- "):
            continue  # list item, belongs to the key above
        m = KEY_RE.match(raw)
        if not m:
            continue
        indent = len(m.group("indent"))
        key = m.group("key").strip().strip("\"'")
        value = m.group("value").strip()
        while stack and stack[-1][0] >= indent:
            stack.pop()
        dotted = ".".join([k for _, k in stack] + [key])
        if "meaning" in block.fields:
            params.append(Param(key=dotted, file=path.name, value=value or "(block)", line=lineno,
                                tier=tier, **{f: block.fields.get(f, "") for f in FIELDS}))
        block.reset()
        if value == "":
            stack.append((indent, key))
    return params


def collect(conf_dir: Path) -> list[Param]:
    out: list[Param] = []
    for path in sorted(conf_dir.glob("parameters*.yml")):
        tier = "user" if path.name == "parameters.yml" else ("reporting" if "reporting" in path.name else "advanced")
        out.extend(parse_file(path, tier))
    return out


BANNER = "GENERATED by scripts/gen_param_docs.py — edit the comment blocks in conf/base/*.yml, not this file."


def render_md(params: list[Param]) -> str:
    lines = [f"<!-- {BANNER} -->", "# ALTR parameters", "",
             f"{len(params)} parameters. Tier `user` = `conf/base/parameters.yml`, the file to edit for a normal run; "
             "`advanced` = per-pipeline files; `reporting` = presentation only.", "",
             "| key | tier | value | unit / range | meaning | default | source | status | file |",
             "|---|---|---|---|---|---|---|---|---|"]
    esc = lambda s: s.replace("|", "\\|")
    for p in params:
        lines.append(f"| `{p.key}` | {p.tier} | `{esc(p.value)}` | {esc(p.unit)} | {esc(p.meaning)} | {esc(p.default)} | {esc(p.source)} | {esc(p.status)} | {p.file}:{p.line} |")
    return "\n".join(lines) + "\n"


